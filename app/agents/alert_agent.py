from email.message import EmailMessage
from html import escape

from app.core.config import settings
from app.core.mailer import deliver
from app.core.story import Story
from app.core.telegram_notifier import TelegramNotifier


def build_alert_html(stories: list[Story]) -> str:
    parts = []
    for s in stories:
        links = " | ".join(
            f'<a href="{escape(link, quote=True)}">{escape(src)}</a>' for src, link in s.sources
        )
        parts.append(
            '<div style="margin-bottom:20px;">'
            f'<h3 style="margin:0 0 6px 0;color:#1a1a1a;">{escape(s.title)}</h3>'
            f'<p style="margin:0 0 6px 0;color:#333;">{escape(s.summary)}</p>'
            f'<p style="margin:0;font-size:13px;color:#666;">{escape(s.credibility)} | '
            f"Sources: {links}</p></div>"
        )
    return (
        '<div style="font-family:Arial,sans-serif;max-width:640px;margin:auto;">'
        '<div style="background:#c53030;color:#fff;padding:10px 14px;font-weight:bold;'
        'letter-spacing:1px;">BREAKING NEWS ALERT</div>'
        f'<div style="padding:16px 0;">{"".join(parts)}</div>'
        '<p style="font-size:12px;color:#999;">Generated by AI Briefing Agent</p>'
        "</div>"
    )


def build_alert_text(stories: list[Story]) -> str:
    lines = ["BREAKING NEWS ALERT", ""]
    for s in stories:
        lines.append(s.title)
        lines.append(s.summary)
        lines.append(s.credibility)
        for src, link in s.sources:
            lines.append(f"   {src}: {link}")
        lines.append("")
    return "\n".join(lines)


def build_alert_message(stories: list[Story], sender: str, receiver: str) -> EmailMessage:
    if len(stories) == 1:
        title = " ".join(stories[0].title.split())[:120]
        subject = f"BREAKING: {title}"
    else:
        subject = f"BREAKING: {len(stories)} critical stories"
    msg = EmailMessage()
    msg["Subject"] = subject
    msg["From"] = sender
    msg["To"] = receiver
    msg.set_content(build_alert_text(stories))
    msg.add_alternative(build_alert_html(stories), subtype="html")
    return msg


def send_alert(stories: list[Story], smtp_class=None) -> None:
    if not stories:
        return
    deliver(
        lambda sender, receiver: build_alert_message(stories, sender, receiver),
        smtp_class=smtp_class,
    )


MAX_TELEGRAM_ALERTS = 5


def build_telegram_text(story: Story) -> str:
    parts = [f"BREAKING: {' '.join(story.title.split())}", "", story.summary.strip(), ""]
    if story.credibility:
        parts.append(story.credibility)
    if story.sources:
        parts.append(story.sources[0][1])
    return "\n".join(parts)


def send_telegram_alert(stories: list[Story], notifier=None) -> int:
    """Critical stories Telegram par bhejta hai. Kabhi exception nahi deta.

    Return: kitne messages gaye. Token/chat id na ho to chupchap 0.
    """
    if not stories:
        return 0
    try:
        notifier = notifier or TelegramNotifier.from_env()
        if not notifier.enabled:
            return 0
        sent = 0
        for story in stories[:MAX_TELEGRAM_ALERTS]:
            if notifier.send(build_telegram_text(story)):
                sent += 1
        return sent
    except Exception:
        return 0


